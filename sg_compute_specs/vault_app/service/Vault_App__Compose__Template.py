# ═══════════════════════════════════════════════════════════════════════════════
# SG/Compute Specs — vault-app: Vault_App__Compose__Template
# Renders the docker-compose.yml the EC2 host writes to /opt/vault-app/.
#
# Two shapes, selected by `with_playwright`:
#   just-vault     (default)  — sg-send-vault only                    (1 container)
#   with-playwright           — + host-plane + sg-playwright + agent-mitmproxy (4 containers)
#
# Only sg-send-vault publishes a host port (8080). Every other service stays on
# the internal vault-net bridge — reach them with an SSM port-forward.
#
# Image sources (all Docker Hub — no ECR):
#   sg-send-vault   → diniscruz/sg-send-vault     (Docker Hub)
#   host-plane      → diniscruz/sg-host-control   (Docker Hub — dedicated small image)
#   sg-playwright   → diniscruz/sg-playwright     (Docker Hub)
#   agent-mitmproxy → mitmproxy/mitmproxy:latest  (Docker Hub OSS)
#   cert-init       → diniscruz/sg-host-control   (Docker Hub — same image, CMD override)
#
# All ${...} values are resolved by the compose engine from /opt/vault-app/.env
# at `up` time — never interpolated here.
# ═══════════════════════════════════════════════════════════════════════════════

from osbot_utils.type_safe.Type_Safe import Type_Safe

SG_SEND_VAULT_IMAGE = 'diniscruz/sg-send-vault:latest'
SG_PLAYWRIGHT_IMAGE = 'diniscruz/sg-playwright:latest'
HOST_CONTROL_IMAGE  = 'diniscruz/sg-host-control'                                   # Docker Hub — dedicated host-control image (no command override needed; CMD baked in)
                                                                                     # Also used by cert-init (same image carries sg_compute.platforms.tls.cert_init)
                                                                                     # Built + pushed by .github/workflows/build-host-control-dockerhub.yml

_HEADER = '''\
# Generated by Vault_App__Compose__Template — do not edit by hand.
services:
'''

_HOST_PLANE = '''
  host-plane:
    image: {host_control_image}:{image_tag}
    ports:
      - "127.0.0.1:19009:8000"   # localhost-only on the EC2 host; reachable via SSM port-forward only
    volumes:
      - {docker_socket}:/var/run/docker.sock
    environment:
      FAST_API__AUTH__API_KEY__NAME:  ${{FAST_API__AUTH__API_KEY__NAME:-X-API-Key}}
      FAST_API__AUTH__API_KEY__VALUE: ${{FAST_API__AUTH__API_KEY__VALUE}}
    networks:
      - vault-net
    restart: unless-stopped
'''

_SG_SEND_VAULT = '''
  sg-send-vault:
    image: {sg_send_vault_image}
{proxy_command}    ports:
      - "8080:8080"
    volumes:
      - ${{VAULT_DATA_PATH:-/opt/vault-app/data}}:/data
{proxy_volume}    environment:
      SGRAPH_SEND__ACCESS_TOKEN:     ${{SGRAPH_SEND__ACCESS_TOKEN}}
      SEND__STORAGE_MODE:            ${{SEND__STORAGE_MODE:-disk}}
      SG_VAULT_APP__SEED_VAULT_KEYS: ${{SG_VAULT_APP__SEED_VAULT_KEYS:-}}
{proxy_env}    networks:
      - vault-net
    restart: unless-stopped
'''

# TLS variant — sg-send-vault terminates its own HTTPS on :443 via the §8.2
# FAST_API__TLS__* contract, reading the cert the one-shot cert-init sidecar
# wrote to the shared volume. Gated behind cert-init via depends_on, so a failed
# issuance means the vault never starts (fail-loud, not silent plain-HTTP).
# With TLS on, the app binds :443 only — :8080 is no longer published.
_SG_SEND_VAULT_TLS = '''
  sg-send-vault:
    image: {sg_send_vault_image}
{proxy_command}    ports:
      - "443:443"
    volumes:
      - ${{VAULT_DATA_PATH:-/opt/vault-app/data}}:/data
      - certs:/certs:ro
{proxy_volume}    environment:
      SGRAPH_SEND__ACCESS_TOKEN:     ${{SGRAPH_SEND__ACCESS_TOKEN}}
      SEND__STORAGE_MODE:            ${{SEND__STORAGE_MODE:-disk}}
      SG_VAULT_APP__SEED_VAULT_KEYS: ${{SG_VAULT_APP__SEED_VAULT_KEYS:-}}
      FAST_API__TLS__ENABLED:        "true"
      FAST_API__TLS__CERT_FILE:      /certs/cert.pem
      FAST_API__TLS__KEY_FILE:       /certs/key.pem
      FAST_API__TLS__PORT:           "443"
{proxy_env}    networks:
      - vault-net
    depends_on:
      cert-init:
        condition: service_completed_successfully
    restart: unless-stopped
'''

_SG_PLAYWRIGHT = '''
  sg-playwright:
    image: {sg_playwright_image}
    ports:
      - "80:8000"                # standard port (Claude/sandbox egress proxies only allow :80/:443); see PLAYWRIGHT_EXTERNAL_PORT
    environment:
      FAST_API__AUTH__API_KEY__NAME:      ${{FAST_API__AUTH__API_KEY__NAME:-X-API-Key}}
      FAST_API__AUTH__API_KEY__VALUE:     ${{FAST_API__AUTH__API_KEY__VALUE}}
      SG_PLAYWRIGHT__DEPLOYMENT_TARGET:   container
      SG_PLAYWRIGHT__DEFAULT_PROXY_URL:   http://agent-mitmproxy:8080
      SG_PLAYWRIGHT__IGNORE_HTTPS_ERRORS: 'true'
      SG_PLAYWRIGHT__ROOT_PATH:           "/pw"                # served behind the vault reverse proxy at /pw — keeps the index UI + /docs prefix-correct
    networks:
      - vault-net
    depends_on:
      agent-mitmproxy:
        condition: service_started
      cert-init:                  # cert-init also binds :80 (http-01 challenge) — wait for it to exit before grabbing the port
        condition: service_completed_successfully
        required: false           # ignored when cert-init isn't in the stack (--no-with-tls-check)
    restart: unless-stopped
'''

_AGENT_MITMPROXY = '''
  agent-mitmproxy:
    image: mitmproxy/mitmproxy:latest
    command:
      - mitmweb
      - --web-host=127.0.0.1
      - --web-port=8081
      - --listen-host=0.0.0.0
      - --listen-port=8080
      - --set
      - block_global=false
    networks:
      - vault-net
    restart: unless-stopped
'''

# One-shot cert sidecar — runs the dedicated host-control Docker Hub image
# (it carries sg_compute.platforms.tls.cert_init alongside the host-plane
# code), writes /certs/{cert,key}.pem, and exits 0. self-signed mode is
# offline; letsencrypt-ip mode runs an http-01 ACME challenge on :80 (hence
# the published port — harmless in self-signed mode, nothing listens after the
# sidecar exits). See the v0.2.6 TLS architecture doc §8.1.
_CERT_INIT = '''
  cert-init:
    image: {host_control_image}:{image_tag}
    command: ["python3", "-m", "sg_compute.platforms.tls.cert_init"]
    environment:
      SG__CERT_INIT__MODE:                  ${{SG__CERT_INIT__MODE:-self-signed}}
      SG__CERT_INIT__COMMON_NAME:           ${{SG__CERT_INIT__COMMON_NAME:-}}
      SG__CERT_INIT__ACME_PROD:             ${{SG__CERT_INIT__ACME_PROD:-false}}
      SG__CERT_INIT__ACME_EMAIL:            ${{SG__CERT_INIT__ACME_EMAIL:-}}
      SG__CERT_INIT__TLS_HOSTNAME:          ${{SG__CERT_INIT__TLS_HOSTNAME:-}}            # FQDN for letsencrypt-hostname mode; ignored for the other modes
      SG__CERT_INIT__DNS_WAIT_TIMEOUT_SEC:  ${{SG__CERT_INIT__DNS_WAIT_TIMEOUT_SEC:-180}}  # letsencrypt-hostname: max seconds cert-init waits for FQDN → my IP convergence before failing (was 900s; v0.1.14 brief)
      FAST_API__TLS__CERT_FILE:   /certs/cert.pem
      FAST_API__TLS__KEY_FILE:    /certs/key.pem
    ports:
      - "80:80"
    volumes:
      - certs:/certs
      - /var/lib/sg-compute:/var/lib/sg-compute                                            # host-shared stage file (cert-init.stage) — sg va check reads it via SSM
    networks:
      - vault-net
    restart: "no"
'''

_NETWORKS = '''
networks:
  vault-net:
    driver: bridge
'''

_VOLUMES = '''
volumes:
  certs:
'''


class Vault_App__Compose__Template(Type_Safe):

    def render(self, with_playwright     : bool = False                       ,
                     image_tag           : str  = 'latest'                    ,
                     sg_send_vault_image : str  = SG_SEND_VAULT_IMAGE          ,
                     sg_playwright_image : str  = SG_PLAYWRIGHT_IMAGE          ,
                     host_control_image  : str  = HOST_CONTROL_IMAGE           ,
                     docker_socket       : str  = '/var/run/docker.sock'      ,
                     with_tls_check      : bool = False                        ) -> str:
        # Runtime-injection reverse proxy: only meaningful with --with-playwright
        # (the only shape with a sg-playwright sibling on vault-net to proxy to).
        # Overrides the container command to our bring-our-own entrypoint, bind-mounts
        # the sg_overrides package, and points /pw/* at the internal Playwright.
        proxy_command = proxy_volume = proxy_env = ''
        if with_playwright:
            proxy_command = '    command: ["python", "-m", "sg_overrides.serve_with_proxy"]\n'
            proxy_volume  = '      - /opt/vault-app/overrides:/app/sg_overrides:ro\n'
            proxy_env     = '      FAST_API__REVERSE_PROXY__ROUTES: "pw=http://sg-playwright:8000"\n'

        vault_block = (_SG_SEND_VAULT_TLS if with_tls_check else _SG_SEND_VAULT)
        parts = [
            _HEADER                                                           ,
            vault_block.format(sg_send_vault_image = sg_send_vault_image ,
                               proxy_command       = proxy_command       ,
                               proxy_volume        = proxy_volume         ,
                               proxy_env           = proxy_env            ),
        ]
        if with_playwright:
            parts.append(_HOST_PLANE.format(host_control_image=host_control_image,
                                            image_tag=image_tag,
                                            docker_socket=docker_socket))
            parts.append(_SG_PLAYWRIGHT.format(sg_playwright_image=sg_playwright_image))
            parts.append(_AGENT_MITMPROXY)
        if with_tls_check:
            parts.append(_CERT_INIT.format(host_control_image=host_control_image,
                                           image_tag=image_tag))
        parts.append(_NETWORKS)
        if with_tls_check:
            parts.append(_VOLUMES)
        return ''.join(parts)
